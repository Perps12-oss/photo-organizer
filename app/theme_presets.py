"""
Named multigradient theme presets for Design System V1.

Each preset defines a full token set plus abstract gradient wash parameters.
Background PNGs are generated by scripts/generate_theme_backgrounds.py.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional

DEFAULT_PRESET_ID = "default"

# (center_x_ratio, center_y_ratio, radius_ratio, rgb, opacity)
GradientWash = tuple[float, float, float, tuple[int, int, int], float]


@dataclass(frozen=True)
class ThemePreset:
    id: str
    label: str
    window_bg: str
    surface_bg: str
    input_bg: str
    border: str
    accent: str
    accent_hover: str
    accent_alt: str
    text_primary: str
    text_secondary: str
    sidebar_tile_active: str
    status_bar_bg: str
    card_shadow: str
    app_primary_text: str
    gradient_base: tuple[int, int, int]
    gradient_washes: tuple[GradientWash, ...] = field(default_factory=tuple)
    sidebar_bg: Optional[str] = None

    @property
    def sidebar_surface(self) -> str:
        return self.sidebar_bg or self.surface_bg


THEME_PRESETS: dict[str, ThemePreset] = {}


def _register(preset: ThemePreset) -> ThemePreset:
    THEME_PRESETS[preset.id] = preset
    return preset


