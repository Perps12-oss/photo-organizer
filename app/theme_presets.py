THEME_PRESET_IDS = tuple(THEME_PRESETS.keys())
THEME_PRESET_LABELS = {p.id: p.label for p in THEME_PRESETS.values()}


def preset_label(preset_id: str) -> str:
    return THEME_PRESET_LABELS.get(preset_id, THEME_PRESET_LABELS[DEFAULT_PRESET_ID])


def normalize_preset_id(value: str | None) -> str:
    if value and value in THEME_PRESETS:
        return value
    return DEFAULT_PRESET_ID


def preset_menu_values() -> list[str]:
    """Display labels for Settings dropdown (label → id resolved on save)."""
    return [p.label for p in THEME_PRESETS.values()]


def preset_id_from_label(label: str) -> str:
    for pid, plabel in THEME_PRESET_LABELS.items():
        if plabel == label:
            return pid
    return DEFAULT_PRESET_ID
